-- One call only: ensure daemon service + reconcile. No parallel watchers.
hl.on("hyprland.start", function()
    hl.exec_cmd("systemctl --user import-environment WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
    hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
    hl.exec_cmd("$HOME/.local/bin/t7-display ensure")
    hl.exec_cmd("$HOME/.local/bin/apply-noctalia-hypr-colors")
    hl.exec_cmd("$HOME/.local/bin/t7-keyboard apply")
end)

hl.on("config.reloaded", function()
    hl.exec_cmd("$HOME/.local/bin/t7-display ensure")
    hl.exec_cmd("$HOME/.local/bin/t7-keyboard apply")
end)

