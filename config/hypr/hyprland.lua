---- MOTION ----
-- Niri used ~320–380ms ease-out curves. Stock Hypr windowsOut (~speed 1.5)
-- feels heavy/old. Higher speed = faster; subtle popin, no bouncy springs.
----------------
hl.curve("outExpo",  { type = "bezier", points = { { 0.16, 1 }, { 0.3, 1 } } })
hl.curve("outCubic", { type = "bezier", points = { { 0.33, 1 }, { 0.68, 1 } } })
hl.curve("outQuad",  { type = "bezier", points = { { 0.25, 1 }, { 0.5, 1 } } })

hl.animation({ leaf = "windows",     enabled = true, speed = 7,  bezier = "outExpo" })
hl.animation({ leaf = "windowsIn",   enabled = true, speed = 7,  bezier = "outExpo",  style = "popin 92%" })
hl.animation({ leaf = "windowsOut",  enabled = true, speed = 8,  bezier = "outCubic", style = "popin 96%" })
hl.animation({ leaf = "windowsMove", enabled = true, speed = 7,  bezier = "outExpo" })
hl.animation({ leaf = "fade",        enabled = true, speed = 7,  bezier = "outQuad" })
hl.animation({ leaf = "fadeIn",      enabled = true, speed = 7,  bezier = "outQuad" })
hl.animation({ leaf = "fadeOut",     enabled = true, speed = 8,  bezier = "outCubic" })
